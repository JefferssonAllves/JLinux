// Run against the private headless fixture, never the user's current desktop.
import {readFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
const require = createRequire(process.env.JLINUX_PLAYWRIGHT_MODULE + '/package.json');
const {chromium} = require('playwright');
const fixture = JSON.parse(await readFile(process.argv[2], 'utf8'));
const browser = await chromium.launch({headless: true});
try {
  const page = await browser.newPage({viewport: {width: 390, height: 844}, isMobile: true, hasTouch: true, deviceScaleFactor: 2});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(fixture.url);
  await page.locator('#key').fill(fixture.key);
  await page.getByRole('button', {name: 'Conectar ao JLinux'}).click();
  await page.waitForFunction(() => document.getElementById('connection').classList.contains('connected'));
  await page.waitForFunction(() => document.getElementById('volume-number').textContent === '42%');
  await page.locator('#volume').evaluate(element => {element.value = 37; element.dispatchEvent(new Event('input'));});
  await page.waitForTimeout(150);
  if (Number(await readFile(fixture.volumeMarker, 'utf8')) !== .37) throw new Error('Volume did not update while dragging');
  await page.locator('#volume').evaluate(element => {for(let value=38;value<=60;value++){element.value=value;element.dispatchEvent(new Event('input'));}element.dispatchEvent(new Event('change'));});
  await page.waitForTimeout(150);
  if (Number(await readFile(fixture.volumeMarker, 'utf8')) !== .60) throw new Error('Final volume was lost');
  await page.waitForFunction(() => document.getElementById('volume-number').textContent === '60%');
  await page.getByRole('button',{name:'Pausar',exact:true}).click();
  await page.getByRole('button',{name:'Reproduzir',exact:true}).waitFor();
  await page.getByRole('button',{name:'Próxima música'}).click();
  await page.getByRole('button',{name:'Música anterior'}).click();
  await page.getByRole('button',{name:'Voltar 10 segundos'}).click();
  await page.getByRole('button',{name:'Avançar 10 segundos'}).click();
  if((await readFile(fixture.mediaActions,'utf8')).trim()!=='play_pause\nnext\nprevious\nseek_back\nseek_forward')throw new Error('Media actions lost');
  await page.screenshot({path: '/tmp/jlinux-connect-mobile.png', fullPage: true});
  await page.evaluate(()=>navigator.serviceWorker.ready);
  await page.waitForFunction(()=>!!navigator.serviceWorker.controller);
  const cached=await page.evaluate(async()=>{const keys=await caches.keys();return (await Promise.all(keys.map(async key=>(await (await caches.open(key)).keys()).map(request=>new URL(request.url).pathname)))).flat();});
  if(cached.some(path=>path.startsWith('/api/')||path.startsWith('/terminal/')))throw new Error('Private data in offline cache');
  await page.context().setOffline(true);
  await page.reload();
  await page.locator('#connecting').waitFor({state:'visible'});
  if(await page.locator('#pair').isVisible())throw new Error('Offline app asked for pairing again');
  await page.context().setOffline(false);
  await page.waitForFunction(()=>document.getElementById('connection').classList.contains('connected'));
  await page.locator('[data-tab=codex]').click();
  await page.waitForFunction(()=>document.querySelectorAll('.agent-group').length===3);
  const groups=await page.locator('.agent-group').evaluateAll(nodes=>nodes.map(node=>({path:node.querySelector('.agent-group-path').textContent,count:node.querySelectorAll('.agent-card').length})));
  if(groups.filter(group=>group.count===2).length!==1 || groups.filter(group=>group.count===1).length!==2 || !groups.some(group=>group.path===''))throw new Error('Chats were not grouped by their exact folder');
  await page.locator('#agent-filter').selectOption('completed');
  await page.getByRole('button',{name:/Outro projeto.*Finalizado · não lido/}).waitFor();
  await page.reload();
  await page.locator('[data-tab=codex]').click();
  await page.locator('#agent-filter').selectOption('completed');
  await page.getByRole('button',{name:/Outro projeto.*Finalizado · não lido/}).click();
  await page.waitForFunction(()=>document.getElementById('agent-title').textContent==='Outro projeto');
  await page.locator('#agents-back').click();
  await page.waitForFunction(()=>document.getElementById('agents-empty').hidden===false);
  await page.reload();
  await page.locator('[data-tab=codex]').click();
  await page.locator('#agent-filter').selectOption('completed');
  await page.waitForFunction(()=>document.getElementById('agents-empty').hidden===false);
  await page.locator('#agent-filter').selectOption('waiting');
  await page.waitForFunction(()=>document.querySelectorAll('.agent-group').length===1 && document.querySelectorAll('.agent-card').length===1);
  await page.locator('#agent-filter').selectOption('all');

  await page.getByRole('button',{name:/Agente aguardando/}).click();
  await page.getByRole('button',{name:'Rosa',exact:true}).click();
  await page.getByRole('button',{name:'Enviar resposta',exact:true}).click();
  await page.waitForFunction(()=>document.getElementById('agent-state').textContent==='Parado');
  await page.locator('#agent-prompt').fill('Continue pelo celular');
  await page.getByRole('button',{name:/Enviar prompt/}).click();
  await page.waitForFunction(()=>document.getElementById('agent-chat').textContent.includes('Prompt recebido pelo agente.'));
  await page.waitForFunction(()=>document.getElementById('agent-chat').textContent.includes('Texto parcial ao vivo'));
  if((await page.locator('#agent-chat').textContent()).includes('resposta completa.'))throw new Error('Text was only shown after completion');
  await page.waitForFunction(()=>document.getElementById('agent-chat').textContent.includes('Texto parcial ao vivo: resposta completa.'));
  if((await page.locator('#agent-chat').textContent()).includes('PRIVATE_STREAM_OUTPUT'))throw new Error('Tool output leaked into live chat');
  if(await readFile(fixture.codexPrompt,'utf8')!=='Continue pelo celular')throw new Error('Prompt did not reach backend');
  await page.screenshot({path:'/tmp/jlinux-connect-codex.png',fullPage:true});
  await page.locator('#agents-back').click();
  await page.getByRole('button',{name:/Agente trabalhando/}).click();
  await page.waitForFunction(()=>document.getElementById('agent-state').textContent==='Trabalhando');

  await page.locator('[data-tab=desktop]').click();
  await page.locator('#screen-toggle').click();
  await page.waitForFunction(() => document.getElementById('message').textContent === 'Tela conectada.', {timeout: 15000});
  await page.waitForFunction(()=>{
    const box=document.getElementById('screen-shell').getBoundingClientRect();
    return Math.abs(box.width-innerWidth)<2 && Math.abs(box.height-innerHeight)<2;
  });
  await page.waitForFunction(()=>{
    const canvas=document.querySelector('#screen canvas');if(!canvas||!canvas.width)return false;
    const data=canvas.getContext('2d').getImageData(0,0,canvas.width,canvas.height).data;
    for(let i=0;i<data.length;i+=16)if(data[i]>70||data[i+1]>70||data[i+2]>70)return true;
    return false;
  });
  await page.waitForFunction(()=>document.getElementById('screen-touchpad').dataset.ready==='true');
  await page.locator('#screen-hide').click();
  if(await page.locator('#screen-exit').isVisible())throw new Error('Fullscreen controls still cover the screen');
  await page.screenshot({path:'/tmp/jlinux-connect-screen-hidden.png',fullPage:true});
  // Exercise Safari's CSS fullscreen fallback when rotating the mobile viewport.
  await page.evaluate(async()=>{if(document.fullscreenElement)await document.exitFullscreen();Object.defineProperty(document,'fullscreenEnabled',{value:false,configurable:true});});
  await page.locator('#screen-expand').click();
  await page.locator('#screen-hide').click();
  await page.setViewportSize({width:844,height:390});
  await page.waitForFunction(()=>{const canvas=document.querySelector('#screen canvas').getBoundingClientRect();return canvas.width<=innerWidth+1 && canvas.height<=innerHeight+1 && canvas.left>=-1 && canvas.top>=-1;});
  await page.screenshot({path:'/tmp/jlinux-connect-screen-landscape.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  const touch=await page.context().newCDPSession(page);
  const gesture=async(type,points)=>touch.send('Input.dispatchTouchEvent',{type,touchPoints:points.map(([x,y,id=1])=>({x,y,id}))});
  await gesture('touchStart',[[50,400]]);
  await gesture('touchMove',[[70,410]]);
  await gesture('touchEnd',[]);
  await gesture('touchStart',[[250,500]]);
  await gesture('touchMove',[[270,510]]);
  await gesture('touchEnd',[]);
  await page.waitForTimeout(200);
  const moves=(await readFile(fixture.pointerMarker,'utf8')).trim().split('\n').filter(line=>line.startsWith('move ')).map(line=>line.split(' ').slice(1).map(Number));
  if(moves.length!==2 || moves.some(([x,y])=>x<=0||y<=0) || Math.abs(moves[0][0]-moves[1][0])>.1 || Math.abs(moves[0][1]-moves[1][1])>.1)throw new Error('Touch movement was not relative across different finger positions');
  await gesture('touchStart',[[50,400],[90,400,2]]);
  await gesture('touchEnd',[]);
  await page.locator('#screen-exit').waitFor({state:'visible'});
  await gesture('touchStart',[[150,400]]);
  await gesture('touchEnd',[]);
  await gesture('touchStart',[[150,400]]);
  await page.waitForTimeout(400);
  await gesture('touchMove',[[170,410]]);
  await gesture('touchEnd',[]);
  await page.waitForTimeout(150);
  const buttons=(await readFile(fixture.pointerMarker,'utf8')).trim().split('\n').filter(line=>line.startsWith('button '));
  if(buttons.join(',')!=='button 1,button 0,button 1,button 0')throw new Error('Relative tap or hold-drag did not release its button');
  await page.locator('#screen-keyboard').click();
  await page.locator('#text').fill(`printf '%s%s\\n' JL_REMOTE _OK > ${fixture.marker}`);
  await page.locator('#typing button').click();
  await page.locator('#enter').click();
  await page.waitForTimeout(500);
  const result = await readFile(fixture.marker, 'utf8');
  if (result.trim() !== 'JL_REMOTE_OK') throw new Error('Remote keyboard did not reach headless terminal');
  await page.screenshot({path: '/tmp/jlinux-connect-desktop.png', fullPage: true});
  await page.locator('#screen-exit').click();
  await page.locator('[data-tab=terminal]').click();
  await page.locator('#terminal-toggle').click();
  const terminal = page.frameLocator('iframe');
  await terminal.locator('.xterm-screen').waitFor();
  await terminal.locator('.xterm-helper-textarea').focus();
  await page.keyboard.type("printf '%s%s\\n' CONNECT_ BROWSER_TEST");
  await page.keyboard.press('Enter');
  await page.waitForTimeout(500);
  if (!await terminal.locator('.xterm-screen').count()) throw new Error('Terminal did not mount');
  await page.locator('#terminal-toggle').click();
  await page.locator('[data-tab=files]').click();
  await page.getByRole('link', {name: 'Baixar do-pc.txt'}).waitFor();
  const downloading = page.waitForEvent('download');
  await page.getByRole('link', {name: 'Baixar do-pc.txt'}).click();
  const downloaded = await downloading;
  if (await readFile(await downloaded.path(), 'utf8') !== 'Arquivo do computador') throw new Error('Download mismatch');
  await page.locator('#file-input').setInputFiles({name:'do-iphone.txt',mimeType:'text/plain',buffer:Buffer.from('Arquivo do iPhone')});
  await page.waitForFunction(() => document.getElementById('upload-status').textContent === 'Arquivos enviados para o JLinux.');
  if (await readFile(fixture.fileRoot + '/do-iphone.txt', 'utf8') !== 'Arquivo do iPhone') throw new Error('Upload mismatch');
  await page.locator('[data-tab=system]').click();
  await page.locator('[data-action=reboot]').click();
  await page.locator('#system-confirm').waitFor({state:'visible'});
  await page.getByRole('button', {name:'Cancelar', exact:true}).click();
  try {await readFile(fixture.actions);throw new Error('Cancelled action executed');}catch(error){if(error.code!=='ENOENT')throw error;}
  await page.locator('[data-action=update]').click();
  await page.locator('#confirm-action').click();
  await page.waitForFunction(() => document.getElementById('update-state').textContent === 'Atualizando…');
  if (!(await page.locator('[data-action=reboot]').isDisabled()) || !(await page.locator('[data-action=poweroff]').isDisabled())) throw new Error('Power actions enabled during update');
  if ((await readFile(fixture.actions,'utf8')).trim() !== 'update') throw new Error('Unexpected action');
  await page.screenshot({path:'/tmp/jlinux-connect-system.png',fullPage:true});
  await page.locator('[data-tab=volume]').click();
  await page.locator('#logout').click();
  await page.locator('#key').waitFor({state: 'visible'});
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('Mobile UI: automatic offline reconnect, media, Codex navigation/question/prompt, fullscreen image, live volume, files, system, terminal passed');
} finally { await browser.close(); }
